<#
.SYNOPSIS
Creates or updates the Azure Load Testing test for a pattern and runs it.

.DESCRIPTION
Stages patterns/<Pattern>/loadtest into .staging, fills the loadtest.yaml tokens from the
deployment outputs and params.json (loadTest), rewrites locust.conf, creates or updates the
test, and starts a test run. The script waits for the run to finish, then waits
params.drainMinutes so the Logic App can drain the queue, and writes results/<Pattern>/last-run.json.
Export-Results.ps1 uses that file for its time window.

.EXAMPLE
./Invoke-LoadTest.ps1 -Pattern 1a-max-throughput
./Invoke-LoadTest.ps1 -Pattern 1a-max-throughput -DurationMinutes 5 -Users 5 -DrainMinutes 5   # short proof run
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$Pattern,
    [int]$DurationMinutes,
    [int]$Users,
    [int]$EngineInstances,
    [int]$BatchSize,
    [double]$BatchesPerUserPerSecond,
    [int]$DrainMinutes = -1,
    [string]$RunLabel,
    [switch]$NoWait
)

. (Join-Path $PSScriptRoot 'Common.ps1')

$kitRoot = Get-KitRoot
$patternDir = Get-PatternDir $Pattern
$params = Get-PatternParams $Pattern
$outputs = Get-DeploymentOutputs $Pattern
$resultsDir = Get-ResultsDir $Pattern
$loadTest = if ($params.loadTest) { $params.loadTest } else { @{} }

function Get-Setting($Override, $Key, $Default) {
    if ($Override) { return $Override }
    if ($null -ne $loadTest[$Key]) { return $loadTest[$Key] }
    $Default
}

$users = Get-Setting $Users 'users' 10
$duration = Get-Setting $DurationMinutes 'durationMinutes' 10
$engines = Get-Setting $EngineInstances 'engineInstances' 1
$batchSize = Get-Setting $BatchSize 'batchSize' 10
$batchRate = Get-Setting $BatchesPerUserPerSecond 'batchesPerUserPerSecond' 1
$spawnRate = if ($loadTest.spawnRate) { $loadTest.spawnRate } else { $users }
$queueName = if ($loadTest.queueName) { $loadTest.queueName } else { '' }
if ($DrainMinutes -lt 0) { $DrainMinutes = if ($null -ne $params.drainMinutes) { $params.drainMinutes } else { 10 } }
$targetRate = $users * $engines * $batchSize * $batchRate

$testId = ("msgpat-$Pattern").ToLowerInvariant() -replace '[^a-z0-9_-]', '-'
if ($testId.Length -gt 50) { $testId = $testId.Substring(0, 50) }

$stagingDir = Join-Path $kitRoot ".staging\$Pattern\loadtest"
if (Test-Path $stagingDir) { Remove-Item $stagingDir -Recurse -Force }
New-Item -ItemType Directory -Force -Path $stagingDir | Out-Null
Copy-Item -Path (Join-Path $patternDir 'loadtest\*') -Destination $stagingDir -Recurse -Force

$tokens = @{
    '__TEST_ID__' = $testId
    '__DISPLAY_NAME__' = "msgpat $Pattern"
    '__PATTERN_ID__' = $Pattern
    '__ENGINE_INSTANCES__' = "$engines"
    '__SB_FQDN__' = $outputs.serviceBusFqdn
    '__SB_QUEUE__' = $queueName
    '__CLIENT_ID__' = $outputs.identityClientId
    '__BATCH_SIZE__' = "$batchSize"
    '__BATCHES_PER_USER_PER_SECOND__' = "$batchRate"
    '__IDENTITY_ID__' = $outputs.identityId
}
$yamlFile = Join-Path $stagingDir 'loadtest.yaml'
$yaml = Get-Content $yamlFile -Raw
foreach ($token in $tokens.Keys) { $yaml = $yaml.Replace($token, $tokens[$token]) }

# params.loadTest.env adds pattern-specific engine variables (for example SB_TOPIC or SESSION_COUNT).
if ($loadTest.env) {
    $extra = ($loadTest.env.Keys | Sort-Object | ForEach-Object { "  - name: $_`n    value: `"$($loadTest.env[$_])`"" }) -join "`n"
    $yaml = $yaml -replace '(?m)^referenceIdentities:', "$extra`nreferenceIdentities:"
}
if ($yaml -match '__[A-Z_]+__') { throw "Unreplaced token in loadtest.yaml: $($Matches[0])" }
Set-Content -Path $yamlFile -Value $yaml -Encoding utf8NoBOM

@(
    '# Generated by Invoke-LoadTest.ps1 from params.json (loadTest).'
    'headless = true'
    "users = $users"
    "spawn-rate = $spawnRate"
    "run-time = ${duration}m"
) | Set-Content -Path (Join-Path $stagingDir 'locust.conf') -Encoding utf8NoBOM

$loadTestName = $outputs.loadTestName
$resourceGroup = $outputs.resourceGroup
Write-Host "Test $testId : $users users x $engines engine(s) x $batchSize msgs x $batchRate/s = $targetRate msg/s for $duration min."

Push-Location $stagingDir
try {
    $exists = az load test show --load-test-resource $loadTestName -g $resourceGroup --test-id $testId --query testId -o tsv 2>$null
    $verb = if ($exists) { 'update' } else { 'create' }
    Write-Host "az load test $verb ..."
    Invoke-Az load test $verb --load-test-resource $loadTestName -g $resourceGroup --test-id $testId `
        --load-test-config-file loadtest.yaml -o none
}
finally { Pop-Location }

$runId = ('run-' + (Get-Date).ToUniversalTime().ToString('yyyyMMdd-HHmmss'))
$label = if ($RunLabel) { $RunLabel } else { "$Pattern $targetRate msg/s ${duration}m" }
$startUtc = (Get-Date).ToUniversalTime()
Invoke-Az load test-run create --load-test-resource $loadTestName -g $resourceGroup --test-id $testId `
    --test-run-id $runId --display-name ($label.Substring(0, [Math]::Min(50, $label.Length))) --no-wait -o none
Write-Host "Started test run $runId at $($startUtc.ToString('o'))."

$record = [ordered]@{
    pattern = $Pattern
    testId = $testId
    testRunId = $runId
    label = $label
    targetMessagesPerSecond = $targetRate
    users = $users
    engineInstances = $engines
    batchSize = $batchSize
    batchesPerUserPerSecond = $batchRate
    durationMinutes = $duration
    drainMinutes = $DrainMinutes
    startUtc = $startUtc.ToString('o')
    loadEndUtc = $null
    endUtc = $null
    status = 'EXECUTING'
}
$lastRunFile = Join-Path $resultsDir 'last-run.json'
$record | ConvertTo-Json | Set-Content $lastRunFile -Encoding utf8NoBOM
if ($NoWait) { return }

$terminal = 'DONE', 'FAILED', 'CANCELLED'
do {
    Start-Sleep -Seconds 30
    $run = az load test-run show --load-test-resource $loadTestName -g $resourceGroup --test-run-id $runId -o json 2>$null | ConvertFrom-Json
    Write-Host "  $(Get-Date -Format HH:mm:ss) status=$($run.status)"
} while ($run -and $run.status -notin $terminal)

$record.status = $run.status
$record.testResult = $run.testResult
$record.loadStartUtc = $run.startDateTime
$record.loadEndUtc = if ($run.endDateTime) { $run.endDateTime } else { (Get-Date).ToUniversalTime().ToString('o') }
$record.portalUrl = $run.portalUrl
$record | ConvertTo-Json | Set-Content $lastRunFile -Encoding utf8NoBOM
$run | ConvertTo-Json -Depth 20 | Set-Content (Join-Path $resultsDir "$runId.alt.json") -Encoding utf8NoBOM

if ($DrainMinutes -gt 0) {
    Write-Host "Load finished ($($run.status)). Waiting $DrainMinutes min for the queue to drain..."
    Start-Sleep -Seconds ($DrainMinutes * 60)
}
$record.endUtc = (Get-Date).ToUniversalTime().ToString('o')
$record | ConvertTo-Json | Set-Content $lastRunFile -Encoding utf8NoBOM
Copy-Item $lastRunFile (Join-Path $resultsDir "$runId.run.json") -Force
Write-Host "Run $runId recorded in $lastRunFile."
